#[derive(Clone, Debug, Default)]
pub struct Constraints {
    pub max_width: Option<f32>,
    pub max_height: Option<f32>,
    pub min_width: f32,
    pub min_height: f32,
}

impl Constraints {
    pub fn loose(max_width: f32) -> Self {
        Self {
            max_width: Some(max_width),
            max_height: None,
            min_width: 0.0,
            min_height: 0.0,
        }
    }

    pub fn tight(max_width: f32, max_height: f32) -> Self {
        Self {
            max_width: Some(max_width),
            max_height: Some(max_height),
            min_width: max_width,
            min_height: max_height,
        }
    }

    pub fn width_limit(&self) -> f32 {
        self.max_width.unwrap_or(f32::INFINITY)
    }
}

pub struct LayoutContext<'a> {
    pub theme: &'a Theme,
    pub viewport_width: f32,
}

impl LayoutContext<'_> {
    pub fn responsive<T: Clone>(&self, value: &crate::responsive::Responsive<T>) -> T {
        value.resolve(self.viewport_width)
    }
}
